"""THE GRAPH'S COMPILE FLAGS AND FACTS, as Starlark: `@fsla_env//:flags.bzl`, written by the environment repository
with the environment's own interpreter from `tools/build_flags.py` -- the one source of the flag list -- so the graph
states no flag of its own.

`NVCC_FLAGS` are the codegen flags without the `-gencode` targets, which the compile rule writes from the build's
architectures; `BUILT_ARCHS` are the registry's built architectures (`hardware.registry.built`), the build's
default; `TORCH` and `CXX11_ABI` are the environment's torch, for the build record. Docs: docs/build-graph.md#compile.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "tools"), str(ROOT)]
import build_flags  # noqa: E402

from hardware import registry  # noqa: E402


def _once(flags: list[str]) -> list[str]:
    return list(dict.fromkeys(flags))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("toolchain", type=Path, help="the toolchain record (tools/toolchains/<name>.json)")
    a = ap.parse_args()
    import torch

    archs = [arch.removeprefix("sm_") for arch in registry.built()]
    nvcc = _once(build_flags.nvcc_flags([]) + list(build_flags.COMMON_NVCC_FLAGS)
                 + build_flags.extension_defines())
    cxx = _once(list(build_flags.HOST_CXX_FLAGS) + build_flags.extension_defines())
    out = ['"""GENERATED by bazel/flags.py from tools/build_flags.py -- do not edit."""', "",
           f"NVCC_FLAGS = {json.dumps(nvcc)}",
           f"HOST_CXX_FLAGS = {json.dumps(cxx)}",
           f"BUILT_ARCHS = {json.dumps(archs)}",
           f"TOOLCHAIN = {json.dumps(a.toolchain.stem)}",
           f"TORCH = {json.dumps(torch.__version__)}",
           f"CXX11_ABI = {bool(torch._C._GLIBCXX_USE_CXX11_ABI)}",
           f"TORCH_CUDA = {json.dumps(torch.version.cuda)}", ""]
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
