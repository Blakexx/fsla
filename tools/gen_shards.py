"""THE ONE ENUMERATION of the carry family's instantiation matrix.

**WHAT THIS OWNS.** ONE closed-world arm list is DEFINED ONCE here -- `CARRY_ARMS`,
the carry family's rows -- and everything that enumerates it is GENERATED from that
definition: one translation unit per arm under `csrc/rola/src/instantiations/`
(KERNEL_STANDARDS section 7, which is what makes an arm-subset build a FILE subset
and lets the arms compile in parallel instead of serially inside one `cicc`), and
`build/generated/carry_selection.inc`, the never-checked-in per-run header naming
which of those rows this build or ratify run actually carries (K36b).

Two independent enumerations of one set is the drift shape this project has already
been bitten by (the shared-router bug), so the list, the macros and the units all
come from `CARRY_ARMS`.

**THE LIST IS EMPTY ON THIS LINE.** C0 deleted the carry family's kernels and the
stats passes with them (card C, `development/queue/C_CLEAN_SLATE.md`), so this
generator emits NO file: there is no arm, no per-arm unit and no instantiation
directory.  What survives is the BUILD's contract -- the table, its final
`(D, DV, warps_per_cta)` key, the shipped/test split and the selection header --
because `setup.py` and `tools/ratify.py` speak it on every run whether or not a row
exists.  G4 refills the list; nothing before it may add a row.

The generated files are CHECKED IN, not built: what is reviewed is what compiles
(closed-world codegen policy). `--check` regenerates into memory and diffs, which is
what CI and `tools/lint/lint_standards.py` run.

Usage:

    python tools/gen_shards.py --write     # regenerate the tree
    python tools/gen_shards.py --check     # regenerate into memory and diff (CI)
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import host_budget  # noqa: E402 -- path insert must precede this import

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "csrc" / "rola" / "src" / "instantiations"

#: THE GENERATED (NEVER CHECKED IN) SELECTION HEADER (K36b).  `setup.py` and
#: `tools/ratify.py` each write `GENERATED_DIR / CARRY_SELECTION_INC` for their own
#: run's arm scope, unconditionally overwriting whatever is there, before compiling
#: any translation unit that includes it.  See `carry_selection_header`.
GENERATED_DIR = ROOT / "build" / "generated"
CARRY_SELECTION_INC = "carry_selection.inc"

BANNER = "// GENERATED by tools/gen_shards.py -- do not edit, regenerate.\n"

# ---------------------------------------------------------------------------
# THE CARRY ARM LIST -- one row per built arm, and THE list.  EMPTY on this line:
# C0 deleted the carry family's kernels (card C, `development/queue/C_CLEAN_SLATE.md`),
# so there is no arm to build and no per-arm translation unit to generate.  The table
# and the selection header it feeds survive because they are the BUILD's contract, not
# the body's: they describe the FINAL key and stay callable with zero rows.
#
# A row is `(D, DV, warps_per_cta)` -- the routing depth, the value width and the CTA's
# warp count.  That is the key the rebuilt family is selected on (K50's 2x4 ruling, card
# C stage C2/G3-G4: `warps_per_cta` in {8, 4}); the mode word, the stream counts and the
# park bit are RUNTIME, not arm axes, and the window and chunk are the descriptor's.
# G4 fills this list; nothing before it may add a row.
CARRY_ARMS: tuple = ()

#: THE SHIPPED / TEST SPLIT (K36).  A default build compiles the SHIPPED rows only;
#: a TEST row is built for the battery and never shipped.  Both are empty while the
#: arm list is (C0): a build carries no carry arm at all.
CARRY_TEST_ARMS: tuple = ()
CARRY_SHIPPED_ARMS: tuple = tuple(i for i in range(len(CARRY_ARMS))
                                  if i not in CARRY_TEST_ARMS)



def carry_kernel_key(row) -> tuple:
    """THE INSTANTIATION an arm's body IS -- and therefore what a TU may hold once.

    Two rows that key the same are ONE kernel and share a file; emitting one kernel
    from two objects is the state `tools/ratify.py` refuses by name.  On the final key
    a row IS its kernel: `(D, DV, warps_per_cta)` selects a body and nothing else does.
    """
    return tuple(row)


def carry_groups() -> dict[int, list[int]]:
    """`{owning arm index -> the arm indices its TU carries}`, in list order.

    The owner is the LOWEST index of the group, which is what names the file.
    """
    by_key: dict = {}
    for i, row in enumerate(CARRY_ARMS):
        by_key.setdefault(carry_kernel_key(row), []).append(i)
    return {members[0]: members for members in
            sorted(by_key.values(), key=lambda m: m[0])}


def carry_tu_of() -> dict[int, int]:
    """`{arm index -> the owning arm index whose file holds it}`."""
    return {i: owner for owner, members in carry_groups().items() for i in members}



def carry_members_sha256() -> str:
    blob = "\n".join(" ".join(str(x) for x in (i,) + row)
                     for i, row in enumerate(CARRY_ARMS)).encode()
    return hashlib.sha256(blob).hexdigest()


def carry_selection_header(arms) -> str:
    """THE GENERATED (never checked in) SELECTION HEADER (K36b).

    Renders `#define ROLA_CARRY_BUILT 1` plus one `#define ROLA_CARRY_BUILD_<i> 1`
    per index in `sorted(set(arms))`. Written by `setup.py` (from `ROLA_CARRY_ARMS`)
    and by `tools/ratify.py` (from the shipped set or a `--carry-arms`/`--arm` scope)
    to `GENERATED_DIR / CARRY_SELECTION_INC` on every run, UNCONDITIONALLY
    OVERWRITING whatever is there -- never accumulated across runs. Included ONLY by
    the carry family's checked-in arm include (the per-arm TUs and the carry dispatch
    TU reach it through that one file), never by anything else, so no other translation
    unit's argv or included content depends on the selection.

    An empty selection (`arms == []`) still emits the `ROLA_CARRY_BUILT` sentinel
    and zero `ROLA_CARRY_BUILD_<i>` lines: a build that selects nothing must still
    satisfy the dispatch TU's include-guard, not silently omit it.
    """
    n = len(CARRY_ARMS)
    bad = sorted({i for i in arms if not 0 <= i < n})
    if bad:
        raise ValueError(f"carry_selection_header: no such carry arm(s) {bad}; "
                         f"the list has {n} rows (0..{n - 1})")
    out = [BANNER,
           "// the CARRY ARM SELECTION for this build/ratify run. NEVER\n",
           "// CHECKED IN; regenerated by setup.py (from ROLA_CARRY_ARMS) and by\n",
           "// tools/ratify.py (from the shipped set or --carry-arms scope) on every run.\n",
           "// Included only by the per-arm TUs and the carry dispatch TU.\n",
           "#define ROLA_CARRY_BUILT 1\n"]
    for i in sorted(set(arms)):
        out.append(f"#define ROLA_CARRY_BUILD_{i} 1\n")
    return "".join(out)


def carry_sources() -> list:
    """`{arm index -> the generated file that carries it}`, for `setup.py`."""
    tu = carry_tu_of()
    return {i: f"carry_arm_{tu[i]}.cu" for i in range(len(CARRY_ARMS))}


def generated() -> dict[str, str]:
    """Every file this generator owns: relative path -> content.

    EMPTY while `CARRY_ARMS` is (C0): the arm list produces one translation unit per
    row and there is no row, so `--write` writes nothing and `--check` asserts that
    the directory holds nothing either.  The generator's remaining output is the
    per-run selection header, which is never checked in and never appears here.
    """
    return {}


_BUILT_LINE_RE = re.compile(r"^#define ROLA_CARRY_BUILT 1$")
_ARM_LINE_RE = re.compile(r"^#define ROLA_CARRY_BUILD_(\d+) 1$")


def _check_carry_selection_schema() -> list[str]:
    """Self-test for `carry_selection_header` (K36b).

    The generated selection header is never checked into the tree, so `--check`
    cannot diff it against a file on disk the way it does the instantiation
    shards; this instead asserts the GENERATOR's schema directly, for the two
    scopes a real build/ratify run actually uses ("all" and the shipped set) plus
    the empty-selection edge case.
    """
    bad: list[str] = []
    cases = {
        "all": list(range(len(CARRY_ARMS))),
        "shipped": list(CARRY_SHIPPED_ARMS),
        "empty": [],
    }
    for name, arms in cases.items():
        text = carry_selection_header(arms)
        lines = [l for l in text.splitlines() if l.startswith("#define")]
        want_n = 1 + len(arms)
        if len(lines) != want_n:
            bad.append(f"    carry_selection_header({name}): {len(lines)} #define "
                       f"lines, expected {want_n} (1 + {len(arms)} arms)")
            continue
        if not _BUILT_LINE_RE.match(lines[0]):
            bad.append(f"    carry_selection_header({name}): first #define line "
                       f"{lines[0]!r} is not the ROLA_CARRY_BUILT sentinel")
            continue
        seen: list[int] = []
        malformed = []
        for line in lines[1:]:
            m = _ARM_LINE_RE.match(line)
            if not m:
                malformed.append(line)
            else:
                seen.append(int(m.group(1)))
        if malformed:
            bad.append(f"    carry_selection_header({name}): malformed #define "
                       f"line(s): {malformed}")
            continue
        if len(seen) != len(set(seen)):
            bad.append(f"    carry_selection_header({name}): duplicate arm index "
                       f"in {seen}")
            continue
        if set(seen) != set(arms):
            bad.append(f"    carry_selection_header({name}): named indices "
                       f"{sorted(set(seen))} != requested {sorted(set(arms))}")
    return bad


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="regenerate the tree")
    ap.add_argument("--check", action="store_true",
                    help="regenerate into memory and fail on any difference")
    a = ap.parse_args()
    if a.write == a.check:
        raise SystemExit("pass exactly one of --write / --check")

    want = generated()
    if a.write:
        #: THE GENERATED TREE, INCLUDING THE SELECTION HEADER, IS ONE SHARED
        #: OUTPUT (LOCKS brief item 3): `tools/ratify.py` writes the same
        #: `CARRY_SELECTION_INC` path unconditionally on every build, so this
        #: CLI's own `--write` must not interleave with that write either.
        with host_budget.file_lock("carry_selection_header"):
            OUT_DIR.mkdir(parents=True, exist_ok=True)
            for name in sorted({p.name for p in OUT_DIR.iterdir() if p.is_file()}):
                if name not in want and name != ".gitkeep":
                    (OUT_DIR / name).unlink()
                    print(f"removed stale {name}")
            for name, text in sorted(want.items()):
                (OUT_DIR / name).write_text(text)
        print(f"wrote {len(want)} files to {OUT_DIR.relative_to(ROOT)}")
        return 0

    bad = []
    on_disk = ({p.name for p in OUT_DIR.iterdir() if p.is_file() and p.name != ".gitkeep"}
               if OUT_DIR.is_dir() else set())
    for name in sorted(on_disk - set(want)):
        bad.append(f"    {name}: on disk, not generated")
    for name, text in sorted(want.items()):
        path = OUT_DIR / name
        if not path.exists():
            bad.append(f"    {name}: missing")
        elif path.read_text() != text:
            bad.append(f"    {name}: differs from the generated content")
    if bad:
        print("FAIL  the checked-in instantiation shards do not match the arm "
              "list in tools/gen_shards.py:")
        print("\n".join(bad))
        print("\n    python tools/gen_shards.py --write")
        return 1

    selection_bad = _check_carry_selection_schema()
    if selection_bad:
        print("FAIL  carry_selection_header's schema self-test failed (K36b; the "
              "generated selection header is never checked in, so this asserts "
              "the generator directly):")
        print("\n".join(selection_bad))
        return 1

    print(f"shards OK  {len(want)} generated files match the {len(CARRY_ARMS)}-row "
          "arm list; carry_selection_header schema OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
