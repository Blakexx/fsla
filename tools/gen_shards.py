def carry_kernel_key(row) -> tuple:
    """THE INSTANTIATION an arm's body IS -- and therefore what a TU may hold once.

    A carved arm takes `carry_kernel`; an arm that carves nothing takes `carry_split_kernel`, whose parameter
    list has no `MO` and no stream counts.  Two rows can therefore be different
    ARMS and one kernel: rows 6 and 7 are the deep-3 topology declared DENSE_BOTH
    and ALT, and the channel-split body ignores the declaration.  Emitting that
    kernel from two translation units is the state `tools/ratify.py` refuses by
    name ("compiled by more than one translation unit"), so the TU is keyed on
    THIS and the rows that share a key share a file.
    """
    (D, DV, W, C, KW, WPS, SPLIT) = row
    if SPLIT:
        return ("split", D, DV, W, C)
    return ("carved", D, DV, W, C, KW, WPS)


def carry_groups() -> dict[int, list[int]]:
    """`{owning arm index -> the arm indices its TU carries}`, in list order.

    The owner is the LOWEST index of the group, which is what names the file.
    """
    by_key: dict = {}
    for i, row in enumerate(CARRY_ARMS):
        by_key.setdefault(carry_kernel_key(row), []).append(i)
    return {members[0]: members for members in
            sorted(by_key.values(), key=lambda m: m[0])}


def carry_tu_of() -> dict[int, int]:
    """`{arm index -> the owning arm index whose file holds it}`."""
    return {i: owner for owner, members in carry_groups().items() for i in members}


#: the span arms are STATELESS only: residency is the paging layer's question and
#: the carry family does not ask it, so no atom-grain row set is emitted.
SPAN_FACTS_MASKS = (1,)


def lex_whole(D: int, B: int, BC: int) -> int:
    for w, lim in ((D, B ** D), (3, B ** 3), (2, B ** 2), (1, B)):
        if lim <= BC:
            return w
    return 0


def lex_span(D: int, B: int, BC: int, l: int) -> int:
    """The lex policy's span at level ``l`` -- the python mirror of the header's.

    A mirror and not an import: the mangled name a manifest keys on carries the
    SPANS now, so this side has to be able to say which spans a `(D, B, BC)` arm
    means, and two derivations disagree exactly when one of them is wrong.
    """
    if l >= D:
        return B
    whole = lex_whole(D, B, BC)
    partial = BC // (B ** whole)
    singles = D - whole - (1 if partial > 1 else 0)
    if l < singles:
        return 1
    if partial > 1 and l == singles:
        return partial
    return B


def lex_spans(D: int, B: int, BC: int) -> tuple:
    return tuple(lex_span(D, B, BC, l) for l in range(4))


#: THE FACTS PASS' CALL-CLASS AXIS: the prefill half of the four masks
#: (`rola/engine/types.py`), and both values are built.  The stateless class
#: compiles no atom-grain emission at all; decode's two masks never reach this
#: kernel and are not instantiated for it.
FACTS_MASKS = (1, 2)


def facts_tables() -> tuple:
    """The `(D, B, BC)` tables the facts pass and the liveness epilogue key on."""
    return tuple(sorted({(a[2], a[3], a[1]) for a in FACTS_ARMS}))


def facts_atom_arms() -> tuple:
    """The STATS pass' REDUCTION arm list: `(D, B)` and nothing else.

    Residency is keyed to the invariant 16-leaf quantum, never to `BC`, so the
    stats pass has no `C` and no `BC` axis and its list is a projection of
    `FACTS_ARMS` -- DERIVED here rather than written out, so the two cannot name
    different topologies and the membership hash covers both.
    """
    return tuple(sorted({(a[2], a[3]) for a in FACTS_ARMS}))


def chunk_rows() -> tuple:
    """Every built facts instantiation, as canonical-hashable tuples."""
    rows = [("FACTS",) + plan + plan[2:] + (m,) for plan in sorted(
        {(d, b) + lex_spans(d, b, bc) for (d, b, bc) in facts_tables()}) for m in FACTS_MASKS]
    rows += [("FACTS",) + plan + (m,) for plan in SPAN_FACTS_ARMS for m in SPAN_FACTS_MASKS]
    rows += [("BLOCK", d, b, bc) for (d, b, bc) in facts_tables()]
    rows += [("ATOM", d, b) for (d, b) in facts_atom_arms()]
    return tuple(sorted(set(rows), key=lambda r: (r[0], r[1:])))


def chunk_canonical(row) -> str:
    return " ".join(str(x) for x in row)


def chunk_members_sha256(rows) -> str:
    blob = "\n".join(sorted(chunk_canonical(r) for r in rows)).encode()
    return hashlib.sha256(blob).hexdigest()


def chunk_shards() -> dict:
    """ONE shard: the facts family is small enough to be one translation unit."""
    return {"facts_s0": list(chunk_rows())}


def shard_manifest_block() -> dict:
    """`{shard: {members_sha256, count}}` -- what `tools/ratify.py` files in the
    per-arch manifests. Membership only: no paths and no ordering, so the digest
    stays a property of the ratification and not of its filing."""
    out = {name: {"members_sha256": chunk_members_sha256(rows), "count": len(rows)}
           for name, rows in sorted(chunk_shards().items())}
    #: THE CARRY ARMS A RATIFICATION COVERS (K36).  The manifest ratifies the SHIPPED
    #: rows; a TEST row is built for the battery and never shipped, so the hash is over
    #: the shipped set and a change to it is a visible re-ratification.
    blob = "\n".join(" ".join(str(x) for x in (i,) + CARRY_ARMS[i])
                     for i in sorted(CARRY_SHIPPED_ARMS)).encode()
    out["carry_shipped"] = {"members_sha256": hashlib.sha256(blob).hexdigest(),
                            "count": len(CARRY_SHIPPED_ARMS)}
    return out


def facts_arms_inc() -> str:
    """The dispatch's arms macro, EMITTED -- one list, one owner."""
    lines = [BANNER,
             f"// members-sha256: {chunk_members_sha256(chunk_rows())}\n",
             "// Included by ../facts/facts_kernel.cuh; the X-macro over every\n",
             "// built (C, BC, D, B) arm of the facts dispatch vocabulary.\n",
             "// clang-format off\n",
             "#define FACTS_ARMS_X(X) \\\n"]
    for i, a in enumerate(FACTS_ARMS):
        tail = "" if i == len(FACTS_ARMS) - 1 else " \\"
        lines.append(f"  X({a[0]}, {a[1]}, {a[2]}, {a[3]}){tail}\n")
    lines.append("// clang-format on\n")
    return "".join(lines)


def facts_shard_source(name: str, rows: list) -> str:
    body = [
        BANNER,
        f"// members-sha256: {chunk_members_sha256(rows)}\n",
        "//\n",
        f"// SHARD {name} -- all {len(rows)} of the facts family's instantiations\n",
        "// (docs/internals/facts/).  The launcher definitions live in\n",
        "// ../facts/facts_launch.cuh; the dispatch TU (../facts/facts.cu) sees\n",
        "// declarations only.\n",
        "\n",
        '#include "../facts/facts_launch.cuh"\n',
        "\n",
        "namespace rola::chunk {\n",
        "\n",
        "//: the FACTS-PASS arms, one per topology x BC x call class.\n",
    ]
    for (d, b, bc) in facts_tables():
        for mask in FACTS_MASKS:
            body.append(f"template cudaError_t launch_chunk_facts_arm<{d}, {b}, {bc}, "
                        f"{mask}>(\n"
                        "    const __nv_bfloat16*, const __nv_bfloat16*, uint32_t*, uint32_t*,\n"
                        "    int, int, cudaStream_t);\n")
    body.append("\n//: the GIVEN-SPAN arms -- the box lattice's owner ballot rows,\n"
                "//: consumed by the rola::carry family (K31-i-d).\n")
    for (d, b, r0, r1, r2, r3, w0, w1, w2, w3) in SPAN_FACTS_ARMS:
        for mask in SPAN_FACTS_MASKS:
            body.append(f"template cudaError_t launch_span_facts_arm<{d}, {b}, {r0}, {r1}, "
                        f"{r2}, {r3}, {w0}, {w1}, {w2}, {w3}, {mask}>(\n"
                        "    const __nv_bfloat16*, const __nv_bfloat16*, uint32_t*, int, int,\n"
                        "    cudaStream_t);\n")
    body.append("\n//: the LIVENESS EPILOGUE's arms -- the same (D, B, BC) key as the\n"
                "//: table it reduces.\n")
    for (d, b, bc) in facts_tables():
        body.append(f"template cudaError_t launch_chunk_block_bitmap_arm<{d}, {b}, {bc}>(\n"
                    "    const uint32_t*, const int32_t*, uint8_t*, int, int, cudaStream_t);\n")
    body.append("\n//: the STATS pass' REDUCTION arms (one per topology) -- keyed (D, B)\n"
                "//: alone, which is the atom bitmap's BC-blindness stated as an\n"
                "//: instantiation list.\n")
    for (d, b) in facts_atom_arms():
        body.append(f"template cudaError_t launch_chunk_atom_bitmap_arm<{d}, {b}>(\n"
                    "    const uint32_t*, uint8_t*, int, int, cudaStream_t);\n")
    body.append("\n}  // namespace rola::chunk\n")
    return "".join(body)


