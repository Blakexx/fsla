"""THE ONE ENUMERATION of the chunk consumer's instantiation matrix.

**WHAT THIS OWNS.** The built arm list `(C, BC, D, B)` is DEFINED ONCE here, and
everything that enumerates it is GENERATED from that definition:

* `csrc/rola/src/instantiations/chunk_s*.cu` -- the shard translation units, each
  carrying `CHUNK_PER_SHARD` arms' explicit instantiations of the host launcher (and
  with them, exactly once in the whole fatbin, that many device kernels);
* `csrc/rola/src/instantiations/chunk_arms.inc` -- the X-macro the kernel header
  walks, plus the stats pass' `(D, B)` projection of the same list;
* `csrc/rola/src/instantiations/scan_arms.inc` -- the X-macro `backward.cu` walks,
  the two scans' own (narrower) arm list;
* `csrc/rola/src/instantiations/README.md` -- the layout, regenerated with them.

Three independent enumerations of one set is the drift shape this project has already
been bitten by once (the shared-router bug agreed with a sibling and disagreed with
the definition), so the arm list, the macro and the shards all come from `CHUNK_ARMS`.

The files are CHECKED IN, not built: what is reviewed must be what compiles
(closed-world codegen policy), and a source file that exists only inside a build
directory cannot be reviewed. `--check` regenerates into memory and diffs, which is
what CI and `tests/unit/test_shard_partition.py` run.

**MEMBERSHIP IS A STRUCTURAL FUNCTION.** A shard is a contiguous slice of
`CHUNK_ARMS` of `CHUNK_PER_SHARD` arms, every kernel variant of an arm riding the
same shard, and nothing else -- no measured compile time, no hand-written file list,
no size threshold. "Rebalance the shards by how long they took to compile last week"
is therefore not a thing that can be expressed here; changing the partition is a
change to `CHUNK_PER_SHARD` and nothing else. `tests/unit/test_shard_partition.py`
asserts every member of every generated file maps back to that file.

**WHY AN ARM LIST AND NOT AN AXIS CROSS.** The level plan's geometry law admits only
certain `(C, BC, D, B)` tuples as built arms, so a cross product would name
unbuildable combinations. The axis that IS crossed is the carried state's I/O
(`compacted_kernel`'s `STATE`), because it is compiled in or out of an arm rather
than being a geometry of its own.

Usage:

    python tools/gen_shards.py --write     # regenerate the tree
    python tools/gen_shards.py --check     # regenerate into memory and diff (CI)
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "csrc" / "rola" / "src" / "instantiations"

#: The formatter the pre-commit hook and CI run, pinned to one version in
#: `.pre-commit-config.yaml`. Generated C++ is piped through it rather than
#: hand-aligned: unformatted generated files would fail either the hook or the
#: regenerate-and-diff gate, and "generated output happens to be formatted" is not a
#: property anybody can maintain by eye.
CLANG_FORMAT = "clang-format"


# ---------------------------------------------------------------------------
# THE EMITTERS
# ---------------------------------------------------------------------------
BANNER = "// GENERATED by tools/gen_shards.py -- do not edit, regenerate.\n"


def _b(v):
    return "true" if v else "false"


def shard_manifest_block() -> dict:
    """`{shard: {members_sha256, count}}` -- what `tools/ratify.py` files in the
    per-arch manifests. Membership only: no paths and no ordering, so the digest
    stays a property of the ratification and not of its filing."""
    return {name: {"members_sha256": chunk_members_sha256(arms), "count": len(arms)}
            for name, arms in sorted(chunk_shards().items())}


README = """\
# `csrc/rola/src/instantiations` — the chunk consumer's explicit-instantiation shards

Every file here is GENERATED by `tools/gen_shards.py` from the single arm list in
that file. Hand-editing one is not a small liberty: the membership hash in its
header, the `shards` block of every ratification manifest and the
regenerate-and-diff gate all disagree with it immediately, and CI fails.

    python tools/gen_shards.py --write     # regenerate
    python tools/gen_shards.py --check     # what CI runs

## What is here

`compacted_kernel<C, BC, D, B, STATE>` has {total} built instantiations —
{narms} arms crossed with the carried state's I/O, the exact set `chunk_forward`
can select, no more and no fewer. They are split across **{nshards} shards of {per} arms**,
whole-program (no `-rdc`), so the compile parallelizes and a ratchet refusal scopes
to one shard's slice of the manifest.

Each shard carries, for its arms: an explicit instantiation of the host launcher
`launch_chunk_arm` (which is what pulls in the device kernel, exactly once in the
whole fatbin) and one of `query_chunk_census_arm`. Shard 0 additionally carries the
union-table and stats arms, which are keyed to the topology rather than to `C`. The
launcher's DEFINITION lives in `../chunk/chunk_launch.cuh`, which `chunk.cu` must
not include — that is what stops the dispatch translation unit from satisfying an
arm by re-instantiating it locally, which would leave the build green and nothing
sharded.

It does NOT make a missing member a link error. This is a Python extension module,
so `ld -shared` leaves the reference undefined for the loader and a dropped arm
would reach a shipped artifact as an `ImportError`. Two gates close it instead:
`python tools/gen_shards.py --check` refuses a shard that disagrees with the arm
list before anything compiles, and `python tools/fatbin_entries.py --check` refuses
a built binary carrying an unresolved `launch_chunk_arm` after the link.

`chunk_arms.inc` carries the X-macro `../chunk/chunk_kernel.cuh` walks to build its
dispatch, plus `CHUNK_ATOM_ARMS_X`, the stats pass' `(D, B)` projection of the same
list. It comes out of the same arm list as the shards, so the dispatch and the
shards cannot enumerate different sets — which is the whole reason this generator
exists.

`scan_arms.inc` carries `SCAN_B_ARMS_X`, the X-macro `../chunk/backward.cu` walks
for the two scans' dispatch, launchers and census. It is a subset of the same arm
list, checked at generation time: a backward arm whose forward is not built could
not run a training step.

## The partition

A shard is a contiguous slice of `CHUNK_ARMS` of `CHUNK_PER_SHARD` arms, every kernel
variant of an arm riding the same shard, and nothing else — membership is a
structural function of the arm, never a measured compile time. Repartitioning is a
change to that one constant.

## The membership hash

Each file's `// members-sha256:` line hashes the SORTED LIST OF ITS TUPLES — not the
file's bytes. A comment edit does not move it; adding, dropping or moving one
instantiation does, and the same hash is recorded in `tools/manifests/sm_*.json`'s
`shards` block, which enters the manifest digest. That is what makes "only shards X
and Y were re-measured" a provable claim.

## The files

| shard | members |
|---|---|
{table}
"""




# ---------------------------------------------------------------------------
# THE ARM LIST -- explicit, not an axis cross: the level plan's geometry law
# admits only these (C, BC, D, B) tuples as built arms, so a cross product
# would name unbuildable combinations.  The launcher definitions live in
# ../chunk/chunk_launch.cuh.
# ---------------------------------------------------------------------------
CHUNK_ARMS: tuple = (
    (16, 64, 2, 8), (32, 64, 2, 8), (64, 64, 2, 8),
    (16, 64, 2, 64), (32, 64, 2, 64), (64, 64, 2, 64),
    (32, 32, 2, 64), (64, 32, 2, 64),
    (16, 128, 2, 64), (32, 128, 2, 64), (64, 128, 2, 64),
    (32, 256, 2, 64),
    (16, 64, 2, 16), (32, 64, 2, 16), (64, 64, 2, 16),
    (32, 128, 3, 16), (32, 128, 4, 8), (32, 32, 4, 8),
    # the FLAT-ROUTING baseline arms (D = 1; N = B <= 256 by the manifest --
    # the benchmark's in-kernel flat control):
    (32, 64, 1, 64), (32, 64, 1, 256), (16, 64, 1, 256),
    # the SCALE rung (N = 65536), whose backward runs at the pinned arm's residency:
    (32, 128, 2, 256),
)
CHUNK_PER_SHARD = 8

#: THE ARMS THE TWO SCANS ARE BUILT FOR -- the reverse pass' own list, and a
#: SUBSET of `CHUNK_ARMS`: a backward whose forward is not built could not run a
#: training step. It is narrower than the forward's because the scans carry the
#: campaign's TRAINABLE topologies, not every arm the forward can infer at
#: (`rola/ops/chunk.py:backward_unsupported` refuses the difference).
SCAN_ARMS: tuple = (
    (32, 128, 2, 64),
    (32, 128, 2, 256),
    (32, 64, 2, 8),
    (32, 64, 2, 16),
    (32, 64, 1, 64),
    (32, 64, 1, 256),
)
assert set(SCAN_ARMS) <= set(CHUNK_ARMS), "every scan arm needs its forward arm"

#: THE STATE AXIS, and BOTH values are built.  The carried state's I/O is compiled
#: in or out (`compacted_kernel`'s `STATE`), so an arm is TWO kernels and the
#: dispatch picks between them on the call's pointers; the ARM LIST is unchanged,
#: because the state is not a geometry.
CHUNK_STATE = (False, True)

def _variants(arm) -> tuple:
    return CHUNK_STATE


def chunk_rows() -> tuple:
    """Every built chunk instantiation: an arm crossed with the state axis."""
    return tuple((*a, s) for a in CHUNK_ARMS for s in _variants(a))


def chunk_atom_arms() -> tuple:
    """The STATS pass' arm list: `(D, B)` and nothing else.

    Residency is keyed to the invariant 16-leaf quantum, never to `BC`, so the
    stats pass has no `C` and no `BC` axis and its list is a projection of
    `CHUNK_ARMS` -- DERIVED here rather than written out, so the two cannot name
    different topologies and the chunk membership hash covers both.
    """
    return tuple(sorted({(a[2], a[3]) for a in CHUNK_ARMS}))


def chunk_canonical(a) -> str:
    return f"C={a[0]} BC={a[1]} D={a[2]} B={a[3]} STATE={_b(a[4])}"


def chunk_members_sha256(rows) -> str:
    blob = "\n".join(sorted(chunk_canonical(r) for r in rows)).encode()
    return hashlib.sha256(blob).hexdigest()


def chunk_shards() -> dict:
    """The partition, still BY ARM: every kernel variant of an arm rides the same
    shard, so a shard is one slice of the geometry and not part of one."""
    return {f"chunk_s{i}": [(*a, s) for a in CHUNK_ARMS[i * CHUNK_PER_SHARD:
                                                        (i + 1) * CHUNK_PER_SHARD]
                            for s in _variants(a)]
            for i in range((len(CHUNK_ARMS) + CHUNK_PER_SHARD - 1) // CHUNK_PER_SHARD)}


def chunk_targs(a) -> str:
    return f"{a[0]}, {a[1]}, {a[2]}, {a[3]}, {_b(a[4])}"


def chunk_arms_inc() -> str:
    """The kernel's arms macro, EMITTED -- one list, one owner (the debt fix:
    this macro and CHUNK_ARMS were one list in two places)."""
    lines = [BANNER,
             f"// members-sha256: {chunk_members_sha256(chunk_rows())}\n",
             "// Included by ../chunk/chunk_kernel.cuh; the X-macro over every\n",
             "// built (C, BC, D, B) arm of the chunk consumer (the swizzle axis\n",
             "// is RETIRED: receipt -2.1..+2.2%, noise, no winner).\n",
             "// clang-format off\n",
             "#define CHUNK_ARMS_X(X) \\\n"]
    for i, a in enumerate(CHUNK_ARMS):
        tail = "" if i == len(CHUNK_ARMS) - 1 else " \\"
        lines.append(f"  X({a[0]}, {a[1]}, {a[2]}, {a[3]}){tail}\n")
    atoms = chunk_atom_arms()
    lines.append("\n// The STATS pass' arms -- (D, B) only, the projection of the\n"
                 "// list above (residency is keyed to the invariant quantum, not BC).\n"
                 "#define CHUNK_ATOM_ARMS_X(X) \\\n")
    for i, a in enumerate(atoms):
        tail = "" if i == len(atoms) - 1 else " \\"
        lines.append(f"  X({a[0]}, {a[1]}){tail}\n")
    lines.append("// clang-format on\n")
    return "".join(lines)


def scan_arms_inc() -> str:
    """The two scans' arms macro, EMITTED: `backward.cu` walks it for the dispatch,
    the launcher, the probe entries and the census, so the reverse pass' arm set has
    one owner exactly as the forward's does."""
    lines = [BANNER,
             "// Included by ../chunk/backward.cu; the X-macro over every\n",
             "// (C, BC, D, B) arm the two scans are built for.\n",
             "// clang-format off\n",
             "#define SCAN_B_ARMS_X(X) \\\n"]
    for i, a in enumerate(SCAN_ARMS):
        tail = "" if i == len(SCAN_ARMS) - 1 else " \\"
        lines.append(f"  X({a[0]}, {a[1]}, {a[2]}, {a[3]}){tail}\n")
    lines.append("// clang-format on\n")
    return "".join(lines)


def chunk_shard_source(name: str, rows: list) -> str:
    arms = rows
    body = [
        BANNER,
        f"// members-sha256: {chunk_members_sha256(rows)}\n",
        "//\n",
        f"// SHARD {name} -- {len(rows)} of the chunk consumer's "
        f"{len(chunk_rows())} instantiations, its arms crossed with the state\n",
        "// axis (docs/internals/chunk/).\n",
        "// The launcher definitions live in ../chunk/chunk_launch.cuh; the\n",
        "// dispatch TU (../chunk/chunk.cu) sees declarations only.\n",
        "\n",
        '#include "../chunk/chunk_launch.cuh"\n',
        "\n",
        "namespace rola::chunk {\n",
        "\n",
    ]
    for a in arms:
        body.append(f"template cudaError_t launch_chunk_arm<{chunk_targs(a)}>("
                    "const ChunkParams&, cudaStream_t);\n")
    body.append("\n")
    for a in arms:
        body.append(
            f"template std::array<int64_t, 9> query_chunk_census_arm<{chunk_targs(a)}>();\n")
    if name == "chunk_s0":
        body.append("\n//: the union-table arms (one per topology x BC) ride shard 0.\n")
        tables = sorted({(a[2], a[3], a[1]) for a in CHUNK_ARMS})
        for (d, b, bc) in tables:
            body.append(f"template cudaError_t launch_chunk_table_arm<{d}, {b}, {bc}>(\n"
                        "    const __nv_bfloat16*, const __nv_bfloat16*, uint32_t*, int, int,\n"
                        "    cudaStream_t);\n")
        body.append("\n//: the LIVENESS EPILOGUE's arms -- the same (D, B, BC) key as the\n"
                    "//: table it reduces.\n")
        for (d, b, bc) in tables:
            body.append(f"template cudaError_t launch_chunk_block_bitmap_arm<{d}, {b}, {bc}>(\n"
                        "    const uint32_t*, const int32_t*, uint8_t*, int, int, cudaStream_t);\n")
        body.append("\n//: the STATS arms (one per topology) ride shard 0 with them.\n")
        for (d, b) in chunk_atom_arms():
            body.append(f"template cudaError_t launch_chunk_atom_table_arm<{d}, {b}>(\n"
                        "    const __nv_bfloat16*, uint32_t*, int, int, cudaStream_t);\n")
        for (d, b) in chunk_atom_arms():
            body.append(f"template cudaError_t launch_chunk_atom_bitmap_arm<{d}, {b}>(\n"
                        "    const uint32_t*, uint8_t*, int, int, cudaStream_t);\n")
    body.append("\n}  // namespace rola::chunk\n")
    return "".join(body)


def readme() -> str:
    sh = chunk_shards()
    table = "\n".join(f"| `{name}.cu` | {len(arms)} |" for name, arms in sorted(sh.items()))
    return README.format(total=len(chunk_rows()), narms=len(CHUNK_ARMS),
                         nshards=len(sh), per=CHUNK_PER_SHARD, table=table)


def generated() -> dict[str, str]:
    """Every file this generator owns: relative path -> content."""
    out = {f"{name}.cu": chunk_shard_source(name, arms)
           for name, arms in sorted(chunk_shards().items())}
    out["chunk_arms.inc"] = chunk_arms_inc()
    out["scan_arms.inc"] = scan_arms_inc()
    for name in list(out):
        out[name] = clang_format(out[name], name)
    out["README.md"] = readme()
    return out


def clang_format(text: str, filename: str) -> str:
    """Pipe generated C++ through the pinned formatter.

    `.inc` is not a language `clang-format` recognizes, so it is formatted as the
    `.cu` fragment it is; the pre-commit hook globs `.cu`/`.cuh` and never sees it,
    but a fragment formatted differently from the file that includes it would be a
    gratuitous inconsistency.
    """
    assume = filename if filename.endswith(".cu") else filename[:-4] + ".cu"
    proc = subprocess.run(
        [CLANG_FORMAT, "--style=file", f"--assume-filename={OUT_DIR / assume}"],
        input=text, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"{CLANG_FORMAT} FAILED on generated {filename}; the "
                         f"generator may not emit files the lint gate would reject")
    return proc.stdout


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="regenerate the tree")
    ap.add_argument("--check", action="store_true",
                    help="regenerate into memory and fail on any difference")
    a = ap.parse_args()
    if a.write == a.check:
        raise SystemExit("pass exactly one of --write / --check")

    want = generated()
    if a.write:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for name in sorted({p.name for p in OUT_DIR.iterdir() if p.is_file()}):
            if name not in want and name != ".gitkeep":
                (OUT_DIR / name).unlink()
                print(f"removed stale {name}")
        for name, text in sorted(want.items()):
            (OUT_DIR / name).write_text(text)
        print(f"wrote {len(want)} files to {OUT_DIR.relative_to(ROOT)} "
              f"({len(chunk_shards())} shards x {CHUNK_PER_SHARD} arms)")
        return 0

    bad = []
    on_disk = {p.name for p in OUT_DIR.iterdir() if p.is_file() and p.name != ".gitkeep"}
    for name in sorted(on_disk - set(want)):
        bad.append(f"    {name}: on disk, not generated")
    for name, text in sorted(want.items()):
        path = OUT_DIR / name
        if not path.exists():
            bad.append(f"    {name}: missing")
        elif path.read_text() != text:
            bad.append(f"    {name}: differs from the generated content")
    if bad:
        print("FAIL  the checked-in instantiation shards do not match the arm "
              "list in tools/gen_shards.py:")
        print("\n".join(bad))
        print("\n    python tools/gen_shards.py --write")
        return 1
    print(f"shards OK  {len(want)} generated files match the arm list "
          f"({len(chunk_rows())} instantiations over {len(chunk_shards())} shards)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
