"""THE ONE ENUMERATION of the facts instantiation matrix.

**WHAT THIS OWNS.** The built arm list `(C, BC, D, B)` is DEFINED ONCE here, and
everything that enumerates it is GENERATED from that definition:

* `csrc/rola/src/instantiations/facts_s0.cu` -- the one shard translation unit,
  carrying every explicit instantiation of the three facts launchers;
* `csrc/rola/src/instantiations/facts_arms.inc` -- the X-macro the facts
  dispatch (`csrc/rola/src/facts/facts.cu`) walks;
* `csrc/rola/src/instantiations/README.md` -- the layout, regenerated with them.

The K31 deletion batch removed the chunk consumer and the two scans (baseline =
tag `baseline/pre-k31`); what remains built is the facts family -- the
union-table pass, the atom-grain stats reduction and the block-grain liveness
epilogue -- and the ARM LIST survives as its dispatch vocabulary: `rola.engine`
folds a topology onto `(C, BC)` against this census, and the facts entries key
on exactly that tuple.  Two independent enumerations of one set is the drift
shape this project has already been bitten by (the shared-router bug), so the
list, the macro and the shard all come from `FACTS_ARMS`.

The files are CHECKED IN, not built: what is reviewed is what compiles
(closed-world codegen policy). `--check` regenerates into memory and diffs,
which is what CI and `tests/unit/test_shard_partition.py` run.

Usage:

    python tools/gen_shards.py --write     # regenerate the tree
    python tools/gen_shards.py --check     # regenerate into memory and diff (CI)
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "csrc" / "rola" / "src" / "instantiations"

#: The formatter the pre-commit hook and CI run, pinned to one version in
#: `.pre-commit-config.yaml`.
CLANG_FORMAT = "clang-format"

BANNER = "// GENERATED by tools/gen_shards.py -- do not edit, regenerate.\n"

README = """\
# `csrc/rola/src/instantiations` — the facts family's explicit-instantiation shard

Every file here is GENERATED by `tools/gen_shards.py` from the single arm list in
that file. Hand-editing one is not a small liberty: the membership hash in its
header, the `shards` block of every ratification manifest and the
regenerate-and-diff gate all disagree with it immediately, and CI fails.

    python tools/gen_shards.py --write     # regenerate
    python tools/gen_shards.py --check     # what CI runs

## What is here

The facts family's launchers, instantiated once each in ONE shard:
`launch_chunk_facts_arm<D, B, BC, MASK>` (one per topology x BC x prefill call
class), `launch_chunk_block_bitmap_arm<D, B, BC>` (the liveness epilogue, the
same key as the table it reduces) and `launch_chunk_atom_bitmap_arm<D, B>` (the
stats reduction, keyed to the invariant 16-leaf quantum and therefore BC-free).
{total} instantiations over {ntables} `(D, B, BC)` tables and {natoms} `(D, B)`
topologies, projected from the {narms}-arm `(C, BC, D, B)` vocabulary.

The launcher DEFINITIONS live in `../facts/facts_launch.cuh`, which the
dispatch TU (`../facts/facts.cu`) must not include — that is what stops it from
satisfying an arm by re-instantiating it locally, which would leave the build
green and nothing sharded. Two gates close the dropped-arm hole:
`python tools/gen_shards.py --check` refuses a shard that disagrees with the
arm list before anything compiles, and `python tools/fatbin_entries.py --check`
refuses a built binary carrying an unresolved launcher after the link.

`facts_arms.inc` carries the X-macro `../facts/facts_kernel.cuh` includes for
the dispatch, out of the same arm list as the shard, so the dispatch and the
shard cannot enumerate different sets.

## The membership hash

The file's `// members-sha256:` line hashes the SORTED LIST OF ITS
INSTANTIATION TUPLES — not the file's bytes. The same hash is recorded in
`tools/manifests/sm_*.json`'s `shards` block, which enters the manifest digest.
"""


# ---------------------------------------------------------------------------
# THE ARM LIST -- the (C, BC, D, B) dispatch vocabulary.  The level plan's
# geometry law admits only certain tuples, so this is a list and never a cross.
# Retained across the K31 consumer deletion: the facts entries and the engine's
# arm fold still speak it, and K31 R2 re-anchors the consumer onto it.
# ---------------------------------------------------------------------------
FACTS_ARMS: tuple = (
    (16, 64, 2, 8), (32, 64, 2, 8), (64, 64, 2, 8),
    (16, 64, 2, 64), (32, 64, 2, 64), (64, 64, 2, 64),
    (32, 32, 2, 64), (64, 32, 2, 64),
    (16, 128, 2, 64), (32, 128, 2, 64), (64, 128, 2, 64),
    (32, 256, 2, 64),
    (16, 64, 2, 16), (32, 64, 2, 16), (64, 64, 2, 16),
    (32, 128, 3, 16), (32, 128, 4, 8), (32, 32, 4, 8),
    # the FLAT-ROUTING baseline arms (D = 1; N = B <= 256 by the manifest):
    (32, 64, 1, 64), (32, 64, 1, 256), (16, 64, 1, 256),
    # the SCALE rung (N = 65536):
    (32, 128, 2, 256),
)

#: THE GIVEN-SPAN FACTS ARMS -- the box lattice's owner rows (K31-i-d).  A row is
#: `(D, B, s_0, s_1, s_2, s_3)`: the owner's per-level SPAN, given rather than
#: derived, with a level past `D` carrying `B` (the identity).  These are the
#: `rola::carry` family's ballot rows, so the list mirrors the carry's built arms
#: -- `tests/unit/test_shard_partition.py` is where the two are held together.
SPAN_FACTS_ARMS: tuple = (
    (2, 256, 8, 16, 256, 256),
    (2, 64, 8, 16, 64, 64),
    (3, 16, 2, 4, 16, 16),
    (4, 8, 2, 2, 4, 8),
    # the CARVE grain: the innermost level's owner run split over the four warps
    # (`BoxPlan::carve_s`), which is the row set the carry's per-warp read lists
    # are scanned from.  An owner-grain word is the OR of a group's four rows.
    (2, 256, 8, 4, 256, 256),
    (2, 64, 8, 4, 64, 64),
    (3, 16, 2, 4, 4, 16),
    (4, 8, 2, 2, 4, 2),
    # the TWO-CARVE grain (K35-E, `TwoCarveRows`): the SAME table refined at BOTH
    # carved levels at once -- the write carve's digit group at `CW` and the read
    # carve's at `CR` -- so each warp reads its own group's row on either side.  A
    # side wanting the owner's run ORs the four rows it already holds.
    (2, 256, 2, 4, 256, 256),
    (2, 64, 2, 4, 64, 64),
    (4, 8, 2, 2, 1, 2),
)

#: the span arms are STATELESS only: residency is the paging layer's question and
#: the carry family does not ask it, so no atom-grain row set is emitted.
SPAN_FACTS_MASKS = (1,)


def lex_whole(D: int, B: int, BC: int) -> int:
    for w, lim in ((D, B ** D), (3, B ** 3), (2, B ** 2), (1, B)):
        if lim <= BC:
            return w
    return 0


def lex_span(D: int, B: int, BC: int, l: int) -> int:
    """The lex policy's span at level ``l`` -- the python mirror of the header's.

    A mirror and not an import: the mangled name a manifest keys on carries the
    SPANS now, so this side has to be able to say which spans a `(D, B, BC)` arm
    means, and two derivations disagree exactly when one of them is wrong.
    """
    if l >= D:
        return B
    whole = lex_whole(D, B, BC)
    partial = BC // (B ** whole)
    singles = D - whole - (1 if partial > 1 else 0)
    if l < singles:
        return 1
    if partial > 1 and l == singles:
        return partial
    return B


def lex_spans(D: int, B: int, BC: int) -> tuple:
    return tuple(lex_span(D, B, BC, l) for l in range(4))


#: THE FACTS PASS' CALL-CLASS AXIS: the prefill half of the four masks
#: (`rola/engine/types.py`), and both values are built.  The stateless class
#: compiles no atom-grain emission at all; decode's two masks never reach this
#: kernel and are not instantiated for it.
FACTS_MASKS = (1, 2)


def facts_tables() -> tuple:
    """The `(D, B, BC)` tables the facts pass and the liveness epilogue key on."""
    return tuple(sorted({(a[2], a[3], a[1]) for a in FACTS_ARMS}))


def facts_atom_arms() -> tuple:
    """The STATS pass' REDUCTION arm list: `(D, B)` and nothing else.

    Residency is keyed to the invariant 16-leaf quantum, never to `BC`, so the
    stats pass has no `C` and no `BC` axis and its list is a projection of
    `FACTS_ARMS` -- DERIVED here rather than written out, so the two cannot name
    different topologies and the membership hash covers both.
    """
    return tuple(sorted({(a[2], a[3]) for a in FACTS_ARMS}))


def facts_plans() -> tuple:
    """Every PLAN the union-table pass is instantiated on, as `(D, B, s_0..s_3)`.

    The kernel is templated on the PLAN TYPE, so its mangled name -- the
    manifest's key -- carries the spans and not the `BC` a lex arm was named by.
    The lex arms project onto their spans here; the given-span arms are already
    spans. Two lex arms that happen to share a plan (a `BC` repeated across chunk
    lengths cannot, but a topology could) resolve to ONE instantiation.
    """
    lex = {(d, b) + lex_spans(d, b, bc) for (d, b, bc) in facts_tables()}
    return tuple(sorted(lex | set(SPAN_FACTS_ARMS)))


def chunk_rows() -> tuple:
    """Every built facts instantiation, as canonical-hashable tuples."""
    rows = [("FACTS",) + plan + (m,) for plan in sorted(
        {(d, b) + lex_spans(d, b, bc) for (d, b, bc) in facts_tables()}) for m in FACTS_MASKS]
    rows += [("FACTS",) + plan + (m,) for plan in SPAN_FACTS_ARMS for m in SPAN_FACTS_MASKS]
    rows += [("BLOCK", d, b, bc) for (d, b, bc) in facts_tables()]
    rows += [("ATOM", d, b) for (d, b) in facts_atom_arms()]
    return tuple(sorted(set(rows), key=lambda r: (r[0], r[1:])))


def chunk_canonical(row) -> str:
    return " ".join(str(x) for x in row)


def chunk_members_sha256(rows) -> str:
    blob = "\n".join(sorted(chunk_canonical(r) for r in rows)).encode()
    return hashlib.sha256(blob).hexdigest()


def chunk_shards() -> dict:
    """ONE shard: the facts family is small enough to be one translation unit."""
    return {"facts_s0": list(chunk_rows())}


def shard_manifest_block() -> dict:
    """`{shard: {members_sha256, count}}` -- what `tools/ratify.py` files in the
    per-arch manifests. Membership only: no paths and no ordering, so the digest
    stays a property of the ratification and not of its filing."""
    return {name: {"members_sha256": chunk_members_sha256(rows), "count": len(rows)}
            for name, rows in sorted(chunk_shards().items())}


def facts_arms_inc() -> str:
    """The dispatch's arms macro, EMITTED -- one list, one owner."""
    lines = [BANNER,
             f"// members-sha256: {chunk_members_sha256(chunk_rows())}\n",
             "// Included by ../facts/facts_kernel.cuh; the X-macro over every\n",
             "// built (C, BC, D, B) arm of the facts dispatch vocabulary.\n",
             "// clang-format off\n",
             "#define FACTS_ARMS_X(X) \\\n"]
    for i, a in enumerate(FACTS_ARMS):
        tail = "" if i == len(FACTS_ARMS) - 1 else " \\"
        lines.append(f"  X({a[0]}, {a[1]}, {a[2]}, {a[3]}){tail}\n")
    lines.append("// clang-format on\n")
    return "".join(lines)


def facts_shard_source(name: str, rows: list) -> str:
    body = [
        BANNER,
        f"// members-sha256: {chunk_members_sha256(rows)}\n",
        "//\n",
        f"// SHARD {name} -- all {len(rows)} of the facts family's instantiations\n",
        "// (docs/internals/facts/).  The launcher definitions live in\n",
        "// ../facts/facts_launch.cuh; the dispatch TU (../facts/facts.cu) sees\n",
        "// declarations only.\n",
        "\n",
        '#include "../facts/facts_launch.cuh"\n',
        "\n",
        "namespace rola::chunk {\n",
        "\n",
        "//: the FACTS-PASS arms, one per topology x BC x call class.\n",
    ]
    for (d, b, bc) in facts_tables():
        for mask in FACTS_MASKS:
            body.append(f"template cudaError_t launch_chunk_facts_arm<{d}, {b}, {bc}, "
                        f"{mask}>(\n"
                        "    const __nv_bfloat16*, const __nv_bfloat16*, uint32_t*, uint32_t*,\n"
                        "    int, int, cudaStream_t);\n")
    body.append("\n//: the GIVEN-SPAN arms -- the box lattice's owner ballot rows,\n"
                "//: consumed by the rola::carry family (K31-i-d).\n")
    for (d, b, s0, s1, s2, s3) in SPAN_FACTS_ARMS:
        for mask in SPAN_FACTS_MASKS:
            body.append(f"template cudaError_t launch_span_facts_arm<{d}, {b}, {s0}, {s1}, "
                        f"{s2}, {s3}, {mask}>(\n"
                        "    const __nv_bfloat16*, const __nv_bfloat16*, uint32_t*, int, int,\n"
                        "    cudaStream_t);\n")
    body.append("\n//: the LIVENESS EPILOGUE's arms -- the same (D, B, BC) key as the\n"
                "//: table it reduces.\n")
    for (d, b, bc) in facts_tables():
        body.append(f"template cudaError_t launch_chunk_block_bitmap_arm<{d}, {b}, {bc}>(\n"
                    "    const uint32_t*, const int32_t*, uint8_t*, int, int, cudaStream_t);\n")
    body.append("\n//: the STATS pass' REDUCTION arms (one per topology) -- keyed (D, B)\n"
                "//: alone, which is the atom bitmap's BC-blindness stated as an\n"
                "//: instantiation list.\n")
    for (d, b) in facts_atom_arms():
        body.append(f"template cudaError_t launch_chunk_atom_bitmap_arm<{d}, {b}>(\n"
                    "    const uint32_t*, uint8_t*, int, int, cudaStream_t);\n")
    body.append("\n}  // namespace rola::chunk\n")
    return "".join(body)


def readme() -> str:
    return README.format(total=len(chunk_rows()), ntables=len(facts_tables()),
                         natoms=len(facts_atom_arms()), narms=len(FACTS_ARMS))


def generated() -> dict[str, str]:
    """Every file this generator owns: relative path -> content."""
    out = {f"{name}.cu": facts_shard_source(name, rows)
           for name, rows in sorted(chunk_shards().items())}
    out["facts_arms.inc"] = facts_arms_inc()
    for name in list(out):
        out[name] = clang_format(out[name], name)
    out["README.md"] = readme()
    return out


def clang_format(text: str, filename: str) -> str:
    """Pipe generated C++ through the pinned formatter.

    `.inc` is not a language `clang-format` recognizes, so it is formatted as the
    `.cu` fragment it is; the pre-commit hook globs `.cu`/`.cuh` and never sees it,
    but a fragment formatted differently from the file that includes it would be a
    gratuitous inconsistency.
    """
    assume = filename if filename.endswith(".cu") else filename[:-4] + ".cu"
    proc = subprocess.run(
        [CLANG_FORMAT, "--style=file", f"--assume-filename={OUT_DIR / assume}"],
        input=text, capture_output=True, text=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"{CLANG_FORMAT} FAILED on generated {filename}; the "
                         f"generator may not emit files the lint gate would reject")
    return proc.stdout


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="regenerate the tree")
    ap.add_argument("--check", action="store_true",
                    help="regenerate into memory and fail on any difference")
    a = ap.parse_args()
    if a.write == a.check:
        raise SystemExit("pass exactly one of --write / --check")

    want = generated()
    if a.write:
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for name in sorted({p.name for p in OUT_DIR.iterdir() if p.is_file()}):
            if name not in want and name != ".gitkeep":
                (OUT_DIR / name).unlink()
                print(f"removed stale {name}")
        for name, text in sorted(want.items()):
            (OUT_DIR / name).write_text(text)
        print(f"wrote {len(want)} files to {OUT_DIR.relative_to(ROOT)}")
        return 0

    bad = []
    on_disk = {p.name for p in OUT_DIR.iterdir() if p.is_file() and p.name != ".gitkeep"}
    for name in sorted(on_disk - set(want)):
        bad.append(f"    {name}: on disk, not generated")
    for name, text in sorted(want.items()):
        path = OUT_DIR / name
        if not path.exists():
            bad.append(f"    {name}: missing")
        elif path.read_text() != text:
            bad.append(f"    {name}: differs from the generated content")
    if bad:
        print("FAIL  the checked-in instantiation shards do not match the arm "
              "list in tools/gen_shards.py:")
        print("\n".join(bad))
        print("\n    python tools/gen_shards.py --write")
        return 1
    print(f"shards OK  {len(want)} generated files match the arm list "
          f"({len(chunk_rows())} instantiations in one shard)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
