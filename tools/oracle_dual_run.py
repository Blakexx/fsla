"""THE DUAL-RUN PROTOCOL: no change to the crown jewels lands without it.

    python tools/oracle_dual_run.py --surface producer --against HEAD~1
    python tools/oracle_dual_run.py --surface oracle   --against HEAD~1 --json run.json
    python tools/oracle_dual_run.py --surface producer --against HEAD~1 --mutate strides

The oracle pair -- `rola/ops/naive.py` and the routing references it composes with --
is what every Tier 1 gate is anchored to. A change to it cannot be reviewed by
reading the diff, because the question is never "is the new code reasonable" but "does
it compute the same function". So both versions are RUN, over a declared matrix, and
compared.

**THE OLD SIDE IS THE PARENT COMMIT'S REAL CODE.** It is checked out into a throwaway
git worktree and run in a SUBPROCESS with that tree on `PYTHONPATH` -- never
re-implemented, never copy-pasted, and never imported under an alias into this
process, where one stale `sys.modules` entry would silently compare a tree against
itself. Everything CPU and fp64: the references are pure torch, so no build is
involved and no device is touched.

**THE MATRIX IS GENERATED BY THIS FILE, AT THIS COMMIT, FOR BOTH SIDES.** The old
tree supplies the library; it never supplies the inputs. Same generator, same seeds,
one library swapped -- which is the only construction under which a difference is
attributable.

Two surfaces, because the two steps of the decomposition have different contracts:

* `--surface producer` -- the routing reference: entmax values, the support SET, the
  VJP, and the composed `routing_factors` / `union_split`. Compared under the
  PRODUCER CONTRACT (P4): `max|dp| <= 1e-13`, `max|dz| <= 1e-13`, and support sets
  equal EXACTLY. Bit-identity is deliberately NOT required here -- the declared
  purpose of that step is to replace a bisection with a third party's closed form,
  so agreement to 1e-14 is the result, and the support-set equality is the claim with
  teeth (a threshold that moves by one entry is a routing change, not rounding).
* `--surface oracle` -- `naive_rola` itself. Compared BY BIT-IDENTITY (P2): both
  sides run fp64 on identical inputs, so a rewrite that only nearly reproduces the
  old one has changed the definition. Declared exceptions are named on the command
  line and asserted individually; anything undeclared is a failure.

**P5, NON-VACUITY.** `--mutate` injects a known defect into the NEW side and the run
must FAIL. A protocol that cannot fail is not a protocol, and this one is the gate
that stands between a quiet oracle change and every Tier 1 claim in the repository.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[1]

#: P4's thresholds, from the measured agreement with one decade of headroom
#: (workflows/refactor/p07_audit.md section 3.2: worst 1.42e-14 forward, 6.66e-16 VJP).
#: The SUPPORT-SET claim carries no tolerance at all, by construction.
PRODUCER_ATOL = 1e-13

#: fp64 seeds. Fixed here rather than passed in: a matrix whose inputs depend on the
#: caller is a matrix two runs can disagree about without either being wrong.
SEED = 20260805


# ---------------------------------------------------------------------------
# THE MATRIX
# ---------------------------------------------------------------------------

def _producer_cells():
    """`(name, logits, mask, alpha)` over logit scale x width x masking.

    The scales are the audit's: 0.5 is a nearly-dense simplex, 3 is the working
    regime, 30 is where a bisection's finite iteration count shows and where two
    implementations are most likely to disagree about the support boundary.
    """
    g = torch.Generator().manual_seed(SEED)
    for width in (3, 16, 256):
        for scale in (0.5, 3.0, 30.0):
            z = torch.randn(8, width, generator=g, dtype=torch.float64) * scale
            for masked in (False, True):
                mask = None
                if masked:
                    mask = torch.ones(8, width, dtype=torch.bool)
                    #: A ragged mask, not a uniform one: padding past `b` is what the
                    #: kernel's `bmask` does, and a uniform mask would exercise none
                    #: of the boundary the mask exists for.
                    for row in range(8):
                        mask[row, max(1, width - row % width):] = False
                for alpha in (1.5, 2.0):
                    yield (f"w{width}-s{scale}-{'masked' if masked else 'dense'}-a{alpha}",
                           z.clone(), mask, alpha)


def _routing_cells():
    """`(name, read_logits, write_logits, mask)` for the COMPOSED reference."""
    g = torch.Generator().manual_seed(SEED + 1)
    for width in (4, 16):
        for scale in (0.5, 3.0, 30.0):
            r = torch.randn(2, 5, width, generator=g, dtype=torch.float64) * scale
            w = torch.randn(2, 5, width, generator=g, dtype=torch.float64) * scale
            yield (f"union-w{width}-s{scale}", r, w, None)


# ---------------------------------------------------------------------------
# THE OLD/NEW SIDE (whichever library is on sys.path)
# ---------------------------------------------------------------------------

def emit_producer() -> dict:
    """Every producer quantity, from whichever `rola` is importable."""
    from rola.routing.entmax.reference import entmax, entmax_forward
    from rola.routing.reference import _union_split_with_support, union_split

    out: dict[str, torch.Tensor] = {}
    for name, z, mask, alpha in _producer_cells():
        p, support, tau = entmax_forward(z, alpha, dim=-1, mask=mask)
        out[f"{name}/p"] = p
        out[f"{name}/support"] = support
        out[f"{name}/tau"] = tau
        #: The VJP through the PUBLIC entry point, with a seeded cotangent -- the
        #: backward is half of what a reference promises and the card's backward
        #: conformance depends on it.
        zg = z.clone().requires_grad_(True)
        pv = entmax(zg, alpha, dim=-1, mask=mask)
        dp = torch.linspace(-1.0, 1.0, pv.numel(), dtype=torch.float64).reshape(pv.shape)
        (dz,) = torch.autograd.grad(pv, zg, grad_outputs=dp)
        out[f"{name}/dz"] = dz

    for name, r, w, mask in _routing_cells():
        read, write = union_split(r, w, alpha=1.5, n_iter=80, mask=mask)
        out[f"{name}/read"] = read
        out[f"{name}/write"] = write
        #: The PACKED support is captured through the private entry point on
        #: purpose: it is the reference's wire format, and a packing change that the
        #: semantic outputs cannot see is exactly what the kernel would then be
        #: gated against.
        out[f"{name}/packed"] = _union_split_with_support(
            r, w, alpha=1.5, n_iter=80, mask=mask)[2]
    return out


def emit_oracle() -> dict:
    """`naive_rola`'s outputs over the structural matrix, forward and backward."""
    from rola.ops.naive import naive_rola
    from rola.routing.types import (
        IndependentRouting,
        LeafMassDecay,
        LevelConfig,
        SoftmaxActivation,
        Topology,
    )

    #: The same routing the Tier 1 matrix uses. The oracle takes ALREADY-NORMALIZED
    #: simplices, so the activation choice never reaches it -- it is here because
    #: `Topology` requires one, and matching Tier 1 keeps the two matrices talking
    #: about the same object.
    routing = IndependentRouting(tied=False, read_activation=SoftmaxActivation(),
                                 write_activation=SoftmaxActivation())

    out: dict[str, torch.Tensor] = {}
    g = torch.Generator().manual_seed(SEED + 2)

    def simplex(shape):
        x = torch.rand(shape, generator=g, dtype=torch.float64) + 1e-3
        return x / x.sum(dim=-1, keepdim=True)

    #: The structural rectangles, the two `d_v`, both normalizations, decay off and
    #: on, and the tile-boundary/ragged `T` values. Named adversarial corners are
    #: mandatory rows, not options (the card's fixture design).
    for widths in ((64, 64), (8, 8, 8, 16), (4, 4)):
        for d_v in (32, 64):
            for normalization in ("raw", "global"):
                for decay_on in (False, True):
                    for T in (1, 17, 37, 64):
                        B, H = 1, 2
                        topo = Topology(
                            levels=tuple(LevelConfig(w, routing) for w in widths),
                            d_v=d_v)
                        read = tuple(simplex((B, T, H, w)) for w in widths)
                        write = tuple(simplex((B, T, H, w)) for w in widths)
                        v = torch.randn(B, T, H, d_v, generator=g, dtype=torch.float64)
                        g_write = torch.rand(B, T, H, generator=g, dtype=torch.float64) + 0.5
                        g_read = (None if normalization == "global"
                                  else torch.rand(B, T, H, generator=g,
                                                  dtype=torch.float64) + 0.5)
                        decay = None
                        if decay_on:
                            dials = tuple(
                                torch.rand(H, w, generator=g, dtype=torch.float64)
                                * 0.3 + 0.1 for w in widths)
                            decay = LeafMassDecay(dials=dials)
                        name = (f"{'x'.join(map(str, widths))}-dv{d_v}-{normalization}-"
                                f"{'decay' if decay_on else 'nodecay'}-T{T}")
                        y, state = naive_rola(
                            v, read, write, g_read, g_write, topo, decay,
                            normalization, output_final_state=True)
                        out[f"{name}/y"] = y
                        out[f"{name}/state"] = state
    return out


SURFACES = {"producer": emit_producer, "oracle": emit_oracle}


# ---------------------------------------------------------------------------
# THE MUTANTS (P5)
# ---------------------------------------------------------------------------

def apply_mutant(kind: str) -> None:
    """Inject a known defect into the NEW side. The run MUST then fail.

    Each mutant is one of the blind spots the protocol exists to cover, so a mutant
    that does not fail names a hole in the comparison rather than a harmless change.
    """
    if kind == "strides":
        #: F3's blind spot: the oracle borrows the leaf-address map from production.
        #: Reversing one stride must be visible; if it is not, the oracle and the
        #: thing it certifies are wrong together.
        import rola.routing.types as types

        original = types.Topology.radix_strides.fget

        def reversed_strides(self):
            got = list(original(self))
            return tuple(got[::-1])

        types.Topology.radix_strides = property(reversed_strides)
    elif kind == "eps":
        #: The readout's epsilon changes the FUNCTION, not its accuracy.
        import rola.ops.naive as naive

        #: `eps` is KEYWORD-ONLY, so it lives in `__kwdefaults__`. Perturbing the
        #: default rather than the call sites is deliberate: it is the same thing a
        #: careless edit to the constant would do.
        naive.naive_rola.__kwdefaults__["eps"] = 2e-5
    elif kind == "support":
        #: One entry pushed out of the support: the claim P4 makes with no tolerance.
        import rola.routing.entmax.reference as ref

        inner = ref.entmax_forward

        def clipped(z, alpha, dim=-1, mask=None, **kw):
            p, support, tau = inner(z, alpha, dim=dim, mask=mask, **kw)
            flat = support.reshape(-1, support.shape[-1])
            for row in range(flat.shape[0]):
                idx = flat[row].nonzero()
                if idx.numel() > 1:
                    flat[row, idx[-1]] = False
                    break
            return p, support, tau

        ref.entmax_forward = clipped
    else:
        raise SystemExit(f"unknown mutant {kind!r}; known: strides, eps, support")
    print(f"MUTANT ACTIVE: {kind}  (this run MUST fail)")


# ---------------------------------------------------------------------------
# THE COMPARISON
# ---------------------------------------------------------------------------

def compare(old: dict, new: dict, *, surface: str, exceptions: set) -> bool:
    only_old = sorted(set(old) - set(new))
    only_new = sorted(set(new) - set(old))
    if only_old or only_new:
        print(f"\nFAIL  the two sides do not answer the same questions: "
              f"{len(only_old)} key(s) only in OLD, {len(only_new)} only in NEW")
        for key in (only_old + only_new)[:8]:
            print(f"        {key}")
        return False

    worst = {"value": 0.0, "key": None}
    failures = []
    for key in sorted(old):
        a, b = old[key], new[key]
        quantity = key.rsplit("/", 1)[-1]
        if a.shape != b.shape:
            failures.append((key, f"shape {tuple(a.shape)} -> {tuple(b.shape)}"))
            continue
        if a.dtype == torch.bool or quantity in ("support", "packed"):
            #: NO TOLERANCE. A support set or a packed word is a discrete claim; one
            #: entry moving is a routing change, not a rounding difference.
            if not torch.equal(a, b):
                differing = int((a != b).sum())
                failures.append((key, f"{differing} discrete entr(ies) differ"))
            continue
        delta = (a.double() - b.double()).abs().max().item()
        if delta > worst["value"]:
            worst = {"value": delta, "key": key}
        if surface == "oracle" and key not in exceptions:
            if not torch.equal(a, b):
                failures.append((key, f"not bit-identical, max|d| = {delta:.3e}"))
        elif delta > PRODUCER_ATOL:
            failures.append((key, f"max|d| = {delta:.3e} > {PRODUCER_ATOL:.0e}"))

    rule = ("BIT-IDENTITY" if surface == "oracle"
            else f"producer contract (atol {PRODUCER_ATOL:.0e}, support sets exact)")
    print(f"\n{len(old)} quantities compared under {rule}")
    print(f"worst continuous difference: {worst['value']:.3e}"
          + (f"  at {worst['key']}" if worst["key"] else ""))
    if exceptions:
        print(f"declared exceptions ({len(exceptions)}): {sorted(exceptions)}")
    if failures:
        print(f"\nFAIL  {len(failures)} quantit(ies) disagree:")
        for key, why in failures[:12]:
            print(f"        {key}: {why}")
        if len(failures) > 12:
            print(f"        ... and {len(failures) - 12} more")
        return False
    print("PASS  dual run")
    return True


def _run_old_side(ref: str, surface: str, out_path: Path) -> None:
    """Check `ref` out into a throwaway worktree and emit its side there."""
    with tempfile.TemporaryDirectory(prefix="rola_dualrun_") as tmp:
        tree = Path(tmp) / "old"
        subprocess.run(["git", "-C", str(ROOT), "worktree", "add", "--detach",
                        str(tree), ref], check=True, capture_output=True, text=True)
        try:
            proc = subprocess.run(
                [sys.executable, str(Path(__file__).resolve()), "--surface", surface,
                 "--emit", str(out_path)],
                cwd=str(tree), env={"PYTHONPATH": str(tree), "PATH": "/usr/bin:/bin"},
                capture_output=True, text=True)
            if proc.returncode != 0:
                sys.stderr.write(proc.stdout + proc.stderr)
                raise SystemExit(f"the OLD side ({ref}) failed to run")
        finally:
            subprocess.run(["git", "-C", str(ROOT), "worktree", "remove", "--force",
                            str(tree)], check=False, capture_output=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--surface", choices=sorted(SURFACES), required=True)
    ap.add_argument("--against", metavar="REF",
                    help="the commit whose oracle is the OLD side (e.g. HEAD~1)")
    ap.add_argument("--emit", metavar="PATH",
                    help="internal: write THIS tree's side and exit")
    ap.add_argument("--mutate", metavar="KIND",
                    help="P5: inject a known defect into the NEW side; the run must fail")
    ap.add_argument("--except", dest="exceptions", action="append", default=[],
                    metavar="KEY", help="a declared P2 exception, repeatable")
    ap.add_argument("--json", metavar="PATH", help="write the record")
    a = ap.parse_args()

    if a.emit:
        torch.save(SURFACES[a.surface](), a.emit)
        return 0
    if not a.against:
        raise SystemExit("--against REF is required (the OLD side is a real commit)")

    if a.mutate:
        apply_mutant(a.mutate)

    with tempfile.TemporaryDirectory(prefix="rola_dualrun_out_") as tmp:
        old_path = Path(tmp) / "old.pt"
        _run_old_side(a.against, a.surface, old_path)
        old = torch.load(old_path, weights_only=False)
    new = SURFACES[a.surface]()

    print(f"OLD = {a.against}   NEW = working tree   surface = {a.surface}")
    ok = compare(old, new, surface=a.surface, exceptions=set(a.exceptions))
    if a.mutate:
        #: The mutant inverts the verdict: a mutant run that PASSES means the
        #: comparison is blind to the defect, which is the failure being tested for.
        if ok:
            print(f"\nP5 FAILED: the protocol PASSED with the {a.mutate!r} mutant "
                  f"active, so it cannot see that class of defect")
            return 1
        print(f"\nP5 PASSED: the protocol rejects the {a.mutate!r} mutant")
        ok = True

    if a.json:
        Path(a.json).write_text(json.dumps(
            {"old": a.against, "surface": a.surface, "mutant": a.mutate,
             "exceptions": sorted(set(a.exceptions)), "quantities": len(new),
             "passed": ok}, indent=1, sort_keys=True) + "\n")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
