"""THE SHARD PARTITION, checked as a structure rather than as a file listing.

The facts family's kernel instantiations live in ONE checked-in translation
unit generated by ``tools/gen_shards.py``. Properties that make that a
partition rather than a habit, each of them a thing that could quietly stop
being true:

1. **Membership is a function of the ARM LIST and nothing else.** The shard's
   instantiations are the projections of ``FACTS_ARMS`` — the declared
   ``(C, BC, D, B)`` dispatch vocabulary — onto the three launcher families
   (facts pass x call class, block bitmap, atom bitmap), so a member is
   determined by the declaration and by no measurement.
2. **The checked-in files are the generated files.** Generated sources are
   committed so that what is reviewed is what compiles; that promise needs a
   gate, and this is the same ``--check`` CI runs.
3. **The dispatch translation unit cannot see the launcher's definition.** If it
   could, it would implicitly instantiate every arm back into itself: the build
   would link, every other gate would stay green, and nothing would be sharded.
   The ``#include`` that would do it is what this test forbids.
4. **The ratification on disk is the one the shipped binary was gated against.**
   Every census and every SASS-body claim in this tree is read out of
   ``tools/manifests/``; if that is not the ratification ``_build_config.py``
   recorded at build time, all of them describe a product nobody built.

That is the whole of what a source-level test can say. It is NOT a claim that a
missing shard member fails the build — it does not, because a Python extension
links with undefined symbols left for the loader, and the failure would
otherwise reach a shipped artifact as an ImportError. The binary-level half is
``tools/fatbin_entries.py``.

**History.** P67 D2-b rewrote this file from the retired tiled consumer's
partition onto the chunk shards; the K31 deletion batch (baseline = tag
``baseline/pre-k31``) rewrote it again onto the facts family's one shard when
the chunk consumer, its state axis and the two scans were deleted. The
structural-membership STANDARD outlives both subjects.

No GPU, no CUDA toolchain, no build — this is a CPU-lane test.
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import subprocess
import sys

import pytest

REPO = pathlib.Path(__file__).resolve().parents[2]
SHARD_DIR = REPO / "csrc" / "rola" / "src" / "instantiations"
sys.path.insert(0, str(REPO / "tools"))

gen_shards = pytest.importorskip("gen_shards")

_FACTS = re.compile(r"template cudaError_t launch_chunk_facts_arm<(\d+), (\d+), (\d+), (\d+)>")
_BLOCK = re.compile(r"template cudaError_t launch_chunk_block_bitmap_arm<(\d+), (\d+), (\d+)>")
_ATOM = re.compile(r"template cudaError_t launch_chunk_atom_bitmap_arm<(\d+), (\d+)>")


def _committed() -> list[tuple]:
    """The shard's members, read off the FILE.

    Off the file and not off the generator's own bookkeeping: the claim is
    about what is COMMITTED, and a generator that agreed with itself would prove
    nothing.
    """
    text = (SHARD_DIR / "facts_s0.cu").read_text()
    rows = [("FACTS", int(d), int(b), int(bc), int(m))
            for d, b, bc, m in _FACTS.findall(text)]
    rows += [("BLOCK", int(d), int(b), int(bc)) for d, b, bc in _BLOCK.findall(text)]
    rows += [("ATOM", int(d), int(b)) for d, b in _ATOM.findall(text)]
    assert rows, "facts_s0.cu instantiates nothing"
    return rows


def test_membership_is_a_function_of_the_arm_list_alone():
    """The shard's members are exactly the generator's projections of
    ``FACTS_ARMS``. Nothing about a member's compile cost, file size or measured
    latency may enter."""
    committed = _committed()
    assert sorted(map(str, committed)) == sorted(map(str, gen_shards.chunk_rows())), (
        "the committed shard and the arm list cover different instantiation sets")


def test_membership_hash_is_over_membership_and_not_over_the_file():
    """The header hash is the sorted tuple list's digest, recomputed here."""
    for name, rows in sorted(gen_shards.chunk_shards().items()):
        text = (SHARD_DIR / f"{name}.cu").read_text()
        stated = re.search(r"^// members-sha256: ([0-9a-f]{64})$", text, re.M)
        assert stated, f"{name}.cu states no membership hash"
        blob = "\n".join(sorted(gen_shards.chunk_canonical(r) for r in rows)).encode()
        assert stated.group(1) == hashlib.sha256(blob).hexdigest()


def test_checked_in_shards_match_the_generator():
    """``gen_shards.py --check`` -- the gate CI and ``setup.py`` both run."""
    proc = subprocess.run([sys.executable, str(REPO / "tools" / "gen_shards.py"), "--check"],
                          cwd=str(REPO), capture_output=True, text=True)
    assert proc.returncode == 0, proc.stdout + proc.stderr


def test_the_dispatch_tu_cannot_satisfy_an_arm_locally():
    """A missing shard member must be UNSATISFIABLE in the dispatch TU.

    ``facts.cu`` reaches every arm through a declared-not-defined launcher.
    Including ``facts_launch.cuh`` would put the launcher's definition in scope
    and let the compiler satisfy the dispatch locally — the exact silent
    non-shard this partition exists to prevent. The binary-level half is
    ``tools/fatbin_entries.py``'s, post-link.
    """
    text = (REPO / "csrc" / "rola" / "src" / "facts" / "facts.cu").read_text()
    assert '#include "facts_launch.cuh"' not in text
    assert '#include "../facts/facts_launch.cuh"' not in text


def test_the_manifest_on_disk_is_the_ratification_the_binary_was_gated_against():
    """Every manifest reader in this tree is reading the SHIPPED ratification.

    ``setup.py`` stamps ``_build_config.py``'s ``manifest_sha256`` with
    ``ratify.manifest_digest`` over the manifest it built against. Recomputing it
    here from ``tools/manifests/`` catches the one failure the readers cannot see
    for themselves: a manifest edited, regenerated or re-filed after the build,
    which would leave every census and every SASS-body claim describing a
    product nobody compiled.

    Through ``tools/ratify.py``'s own functions deliberately — the question is
    whether the FILES moved, not whether two canonicalizations agree, and a
    second implementation here would answer a different question and drift.
    """
    from rola._build_config import BUILD_CONFIG

    ratify = pytest.importorskip("ratify")
    arches = sorted(p.stem.removeprefix("sm_")
                    for p in (REPO / "tools" / "manifests").glob("sm_*.json"))
    assert arches, "no ratification manifest on disk"
    got = ratify.manifest_digest(ratify.load_manifest(arches))
    assert got == BUILD_CONFIG["manifest_sha256"], (
        f"the manifests on disk digest to {got}, which is NOT the ratification "
        f"the shipped binary was gated against ({BUILD_CONFIG['manifest_sha256']}). "
        "Every reader of tools/manifests/ is then describing a product that was "
        "never built.")
