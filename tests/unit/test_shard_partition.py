"""THE SHARD PARTITION, checked as a structure rather than as a file listing.

The consumer's 512 kernel instantiations are split across eight checked-in
translation units generated by ``tools/gen_shards.py``. Three properties make that
split a partition rather than a habit, and each of them is a thing that could quietly
stop being true:

1. **Membership is a structural function.** ``shard_of`` reads a template tuple and
   nothing else -- no measured compile time, no file size, no threshold. A future
   "rebalance the shards, ``consumer_bf16_raw_bt16`` is the slow one" is refused by
   this test rather than by anybody remembering the standing rule.
2. **The checked-in files are the generated files.** Generated sources are committed
   so that what is reviewed is what compiles; that promise needs a gate, and this is
   the same ``--check`` CI runs.
3. **The dispatch translation unit cannot see the launcher's definition.** If it
   could, it would implicitly instantiate all 512 kernels back into itself: the build
   would link, every other gate would stay green, and nothing would be sharded. The
   ``#include`` that would do it is what this test forbids; the OUTCOME is proved
   from the built binary by ``tools/fatbin_entries.py``, which is a different
   question and deliberately a second gate.

No GPU, no CUDA toolchain, no build -- this is a CPU-lane test.
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import subprocess
import sys

import pytest

REPO = pathlib.Path(__file__).resolve().parents[2]
SHARD_DIR = REPO / "csrc" / "rola" / "src" / "instantiations"
sys.path.insert(0, str(REPO / "tools"))

gen_shards = pytest.importorskip("gen_shards")


def test_membership_is_a_function_of_the_tuple_alone():
    """Every member of every generated file maps back to that file under ``shard_of``.

    Read off the FILES, not off the generator's own bookkeeping: the claim is about
    what is committed, and a generator that agreed with itself would prove nothing.
    """
    pattern = re.compile(
        r"template void launch_consumer_arm<"
        r"(\d+), (\d+), (\d+), (\d+), MmaPrec::(kBf16|kTf32x3), "
        r"(true|false), (true|false), (true|false)>")
    seen: dict[str, str] = {}
    for path in sorted(SHARD_DIR.glob("consumer_*.cu")):
        rows = pattern.findall(path.read_text())
        assert len(rows) == gen_shards.TARGET_MEMBERS_PER_SHARD, (
            f"{path.name} carries {len(rows)} instantiations, not "
            f"{gen_shards.TARGET_MEMBERS_PER_SHARD}")
        for BT, BC, DV, D, prec, decay, glob, compact in rows:
            row = dict(BT=int(BT), BC=int(BC), DV=int(DV), D=int(D),
                       PREC="bf16" if prec == "kBf16" else "tf32x3",
                       DECAY=decay == "true", GLOBAL=glob == "true",
                       COMPACT=compact == "true")
            key = gen_shards.canonical(row)
            assert key not in seen, f"{key} is instantiated in two shards"
            seen[key] = path.stem
            assert gen_shards.shard_of(row) == path.stem, (
                f"{key} is in {path.stem} but shard_of() says "
                f"{gen_shards.shard_of(row)}")
    assert set(seen) == {gen_shards.canonical(r) for r in gen_shards.matrix()}, (
        "the committed shards and the matrix definition cover different sets")


def test_the_partition_is_driven_by_the_priority_list_and_the_target():
    """The sharded axes are DERIVED, so a re-partition is a two-constant change.

    The test states the derivation rather than the answer: it asserts that the axes
    in use are exactly the shortest prefix of ``SHARD_AXIS_PRIORITY`` that reaches
    the target, which stays true across P17's read-path axis without an edit here.
    """
    axes = gen_shards.shard_axes()
    assert axes == gen_shards.SHARD_AXIS_PRIORITY[:len(axes)]
    reach = 1
    for name in axes:
        reach *= len(gen_shards.AXIS[name].values)
    total = len(gen_shards.matrix())
    assert reach * gen_shards.TARGET_MEMBERS_PER_SHARD >= total
    shorter = reach // len(gen_shards.AXIS[axes[-1]].values)
    assert shorter * gen_shards.TARGET_MEMBERS_PER_SHARD < total, (
        "the partition uses more axes than the target requires")


def test_membership_hash_is_over_membership_and_not_over_the_file():
    """The header hash is the sorted tuple list's digest, recomputed here."""
    for name, rows in sorted(gen_shards.shards().items()):
        text = (SHARD_DIR / f"{name}.cu").read_text()
        stated = re.search(r"^// members-sha256: ([0-9a-f]{64})$", text, re.M)
        assert stated, f"{name}.cu states no membership hash"
        blob = "\n".join(sorted(gen_shards.canonical(r) for r in rows)).encode()
        assert stated.group(1) == hashlib.sha256(blob).hexdigest()


def test_checked_in_shards_match_the_generator():
    """``gen_shards.py --check`` -- the gate CI and ``setup.py`` both run."""
    proc = subprocess.run([sys.executable, str(REPO / "tools" / "gen_shards.py"), "--check"],
                          cwd=str(REPO), capture_output=True, text=True)
    assert proc.returncode == 0, proc.stdout + proc.stderr


@pytest.mark.parametrize("header", ["consumer_launch.cuh", "consumer_kernel.cuh"])
def test_the_dispatch_tu_cannot_instantiate_the_kernel(header):
    """A missing shard member must be a LINK ERROR, never a re-instantiation.

    ``consumer.cu`` reaches every arm through a declared-not-defined host wrapper.
    Including either of these headers would put the kernel template's definition in
    scope and let the compiler satisfy the dispatch locally -- the exact silent
    non-shard this partition exists to prevent.
    """
    text = (REPO / "csrc" / "rola" / "src" / "consumer.cu").read_text()
    assert f'#include "{header}"' not in text
