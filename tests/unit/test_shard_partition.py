"""THE SHARD PARTITION, checked as a structure rather than as a file listing.

The chunk consumer's kernel instantiations are split across checked-in
translation units generated by ``tools/gen_shards.py``. Properties that make
that split a partition rather than a habit, each of them a thing that could
quietly stop being true:

1. **Membership is a function of the ARM LIST and nothing else.** A shard is a
   contiguous block of ``CHUNK_ARMS`` — the declared enumeration of built
   ``(C, BC, D, B)`` tuples — crossed with the state axis, so an arm's shard is
   determined by the declaration and by no measurement. A future "rebalance the
   shards, that one is the slow one" is refused by this test rather than by
   somebody remembering the standing rule. Both state variants of an arm ride
   the SAME shard, so a shard is one slice of the geometry and not half of one.
2. **The checked-in files are the generated files.** Generated sources are
   committed so that what is reviewed is what compiles; that promise needs a
   gate, and this is the same ``--check`` CI runs.
3. **The dispatch translation unit cannot see the launcher's definition.** If it
   could, it would implicitly instantiate every arm back into itself: the build
   would link, every other gate would stay green, and nothing would be sharded.
   The ``#include`` that would do it is what this test forbids.
4. **The ratification on disk is the one the shipped binary was gated against.**
   Every census, every SASS-body claim and every occupancy bound in this tree is
   read out of ``tools/manifests/``; if that is not the ratification
   ``_build_config.py`` recorded at build time, all of them describe a product
   nobody built.

That is the whole of what a source-level test can say. It is NOT a claim that a
missing shard member fails the build — it does not, because a Python extension
links with undefined symbols left for the loader, and the failure would
otherwise reach a shipped artifact as an ImportError. The binary-level half is
``tools/fatbin_entries.py``: one device entry per instantiation in its assigned
shard, no unresolved per-arm wrapper, and every ratified name present. Two
gates, two questions, deliberately.

**P67 D2-b rewrote this file for the chunk shards** (ruling R-9). Its subject
was the retired tiled consumer's 256 instantiations across eight shards, matched
by source-file name. The structural-membership STANDARD outlives it, so the
file was rewritten rather than deleted. Two claims changed shape with the
subject and are recorded here rather than silently dropped:

* the tiled partition derived its sharded AXES from a priority list and a
  member target (``SHARD_AXIS_PRIORITY``, ``TARGET_MEMBERS_PER_SHARD``), so a
  re-partition was a two-constant change. The chunk matrix is an explicit ARM
  LIST and not an axis cross — the level plan's geometry law admits only certain
  ``(C, BC, D, B)`` tuples, so a cross product would name unbuildable
  combinations — and a list has no axes to prioritize. What replaces that claim
  is the block rule below, which is the same statement (membership is derived,
  not assigned) over the structure the chunk matrix actually has.
* ``census()``'s manifest pin arrived here from
  the retired ``test_meta.py``, which went with the geometry matrix.
  It is not a matrix claim: it is the claim that every manifest reader in the
  tree is reading the shipped ratification.

No GPU, no CUDA toolchain, no build — this is a CPU-lane test.
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import subprocess
import sys

import pytest

REPO = pathlib.Path(__file__).resolve().parents[2]
SHARD_DIR = REPO / "csrc" / "rola" / "src" / "instantiations"
sys.path.insert(0, str(REPO / "tools"))

gen_shards = pytest.importorskip("gen_shards")

#: `<C, BC, D, B, STATE>` off a committed shard's own text.
_ARM = re.compile(
    r"template cudaError_t launch_chunk_arm<"
    r"(\d+), (\d+), (\d+), (\d+), (true|false)>")


def _committed() -> dict[str, list[tuple]]:
    """Every generated shard's members, read off the FILES.

    Off the files and not off the generator's own bookkeeping: the claim is
    about what is COMMITTED, and a generator that agreed with itself would prove
    nothing.
    """
    out: dict[str, list[tuple]] = {}
    for path in sorted(SHARD_DIR.glob("chunk_s*.cu")):
        rows = [(int(c), int(bc), int(d), int(b), state == "true")
                for c, bc, d, b, state in _ARM.findall(path.read_text())]
        assert rows, f"{path.name} instantiates no chunk arm"
        out[path.stem] = rows
    assert out, f"no chunk shards in {SHARD_DIR}"
    return out


def test_membership_is_a_function_of_the_arm_list_alone():
    """An arm's shard is its BLOCK in ``CHUNK_ARMS``, and every kernel variant of
    an arm rides together. Nothing about a member's compile cost, file size or
    measured latency may enter."""
    committed = _committed()
    per_shard = gen_shards.CHUNK_PER_SHARD
    seen: dict[tuple, str] = {}
    for name, rows in committed.items():
        index = int(name.removeprefix("chunk_s"))
        block = gen_shards.CHUNK_ARMS[index * per_shard:(index + 1) * per_shard]
        expected = [(*arm, state) for arm in block for state in gen_shards.CHUNK_STATE]
        assert rows == expected, (
            f"{name}.cu's members are not block {index} of CHUNK_ARMS crossed "
            "with the state axis, in declaration order")
        for row in rows:
            assert row not in seen, f"{row} is instantiated in {seen[row]} and {name}"
            seen[row] = name
    assert set(seen) == set(gen_shards.chunk_rows()), (
        "the committed shards and the arm list cover different instantiation sets")


def test_every_variant_of_an_arm_shares_a_shard():
    """A shard is one slice of the GEOMETRY. The carried state's I/O is compiled
    in or out of the same arm, so splitting the two variants across shards would
    make a shard part of one geometry — and would let one variant be dropped while
    its twin stayed, which no membership hash over arms would notice."""
    for name, rows in _committed().items():
        by_arm: dict[tuple, set] = {}
        for *arm, state in rows:
            by_arm.setdefault(tuple(arm), set()).add(state)
        for arm, variants in by_arm.items():
            assert variants == set(gen_shards.CHUNK_STATE), (
                f"{name}.cu carries arm {arm} at variants {sorted(variants)} only")


def test_membership_hash_is_over_membership_and_not_over_the_file():
    """The header hash is the sorted tuple list's digest, recomputed here."""
    for name, rows in sorted(gen_shards.chunk_shards().items()):
        text = (SHARD_DIR / f"{name}.cu").read_text()
        stated = re.search(r"^// members-sha256: ([0-9a-f]{64})$", text, re.M)
        assert stated, f"{name}.cu states no membership hash"
        blob = "\n".join(sorted(gen_shards.chunk_canonical(r) for r in rows)).encode()
        assert stated.group(1) == hashlib.sha256(blob).hexdigest()


def test_checked_in_shards_match_the_generator():
    """``gen_shards.py --check`` -- the gate CI and ``setup.py`` both run."""
    proc = subprocess.run([sys.executable, str(REPO / "tools" / "gen_shards.py"), "--check"],
                          cwd=str(REPO), capture_output=True, text=True)
    assert proc.returncode == 0, proc.stdout + proc.stderr


def test_the_dispatch_tu_cannot_satisfy_an_arm_locally():
    """A missing shard member must be UNSATISFIABLE in the dispatch TU.

    ``chunk.cu`` reaches every arm through a declared-not-defined host wrapper
    (``chunk_kernel.cuh``). Including ``chunk_launch.cuh`` would put the
    launcher's definition in scope and let the compiler satisfy the dispatch
    locally — the exact silent non-shard this partition exists to prevent.

    What this does NOT establish is that a missing member fails the BUILD. It
    does not: a Python extension links with undefined symbols left for the
    loader, so a dropped arm would reach a shipped artifact as an ImportError.
    That is ``tools/fatbin_entries.py``'s job, post-link.
    """
    text = (REPO / "csrc" / "rola" / "src" / "chunk" / "chunk.cu").read_text()
    assert '#include "chunk_launch.cuh"' not in text
    assert '#include "../chunk/chunk_launch.cuh"' not in text


def test_the_manifest_on_disk_is_the_ratification_the_binary_was_gated_against():
    """Every manifest reader in this tree is reading the SHIPPED ratification.

    ``setup.py`` stamps ``_build_config.py``'s ``manifest_sha256`` with
    ``ratify.manifest_digest`` over the manifest it built against. Recomputing it
    here from ``tools/manifests/`` catches the one failure the readers cannot see
    for themselves: a manifest edited, regenerated or re-filed after the build,
    which would leave every census, every SASS-body claim and every occupancy
    bound describing a product nobody compiled.

    Through ``tools/ratify.py``'s own functions deliberately — the question is
    whether the FILES moved, not whether two canonicalizations agree, and a
    second implementation here would answer a different question and drift.
    """
    from rola._build_config import BUILD_CONFIG

    ratify = pytest.importorskip("ratify")
    arches = sorted(p.stem.removeprefix("sm_")
                    for p in (REPO / "tools" / "manifests").glob("sm_*.json"))
    assert arches, "no ratification manifest on disk"
    got = ratify.manifest_digest(ratify.load_manifest(arches))
    assert got == BUILD_CONFIG["manifest_sha256"], (
        f"the manifests on disk digest to {got}, which is NOT the ratification "
        f"the shipped binary was gated against ({BUILD_CONFIG['manifest_sha256']}). "
        "Every reader of tools/manifests/ is then describing a product that was "
        "never built.")
